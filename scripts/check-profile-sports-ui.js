import { chromium,expect } from '@playwright/test';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import { mkdir } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PrismaClient,Prisma } from '../prisma/client/index.js';
import { createApp } from '../server/app.js';
import { readConfig } from '../server/config.js';
const url=new URL(process.env.TEST_DATABASE_URL);
if(!['localhost','127.0.0.1'].includes(url.hostname)||url.pathname!=='/invictus_test')throw Error('Solo invictus_test local');
const db=new PrismaClient({datasources:{db:{url:url.href}}});
const origin='http://localhost:5174';
const app=await createApp({database:db,Prisma,config:readConfig({...process.env,DATABASE_URL:url.href,NODE_ENV:'test',STORAGE_DRIVER:'local',WEB_ORIGINS:origin,UPLOAD_DIRECTORY:'.local/test-uploads'})});
const server=app.listen(3101);let vite,browser;
try {
  vite=await createServer({configFile:false,root:'client',plugins:[react()],server:{host:'localhost',port:5174,strictPort:true,proxy:{'/api':'http://localhost:3101'}}});await vite.listen();
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const username='ui_'+randomUUID().replaceAll('-','').slice(0,24),email=randomUUID()+'@example.test';
  const registered=await page.request.post(origin+'/api/auth/register',{headers:{Origin:origin},data:{username,email,password:'abcdefgh'}});
  expect(registered.status()).toBe(201);
  await page.goto(origin+'/#/perfil');await page.getByRole('heading',{name:'Perfil',exact:true}).waitFor();
  await expect(page.getByLabel('Nombre de usuario')).toHaveValue(username);

  await page.getByRole('tab',{name:'Deportes',exact:true}).click();
  await page.getByRole('button',{name:'Agregar Running',exact:true}).click();
  const selected=page.getByRole('button',{name:'Seleccionado: Running',exact:true});
  await expect(selected).toHaveAttribute('aria-pressed','true');await selected.click();
  await expect(page.locator('.profile-sports-selected>li')).toHaveCount(1);
  await expect(page.locator('.profile-sports-selected').getByText('Principal',{exact:true})).toBeVisible();
  await page.getByRole('textbox',{name:'Buscar deporte',exact:true}).fill('NATA');
  await page.getByRole('button',{name:'Agregar Natación',exact:true}).click();
  await page.getByRole('button',{name:'Marcar Natación como principal',exact:true}).click();
  await page.getByRole('textbox',{name:'Buscar deporte',exact:true}).fill('noexiste123');
  await expect(page.getByText('No encontramos deportes con ese nombre.',{exact:true})).toBeVisible();
  await page.getByRole('textbox',{name:'Buscar deporte',exact:true}).fill('');
  await page.getByRole('button',{name:'Guardar deportes',exact:true}).click();
  await expect(page.getByText('Deportes guardados.',{exact:true})).toBeVisible();
  await expect(page.locator('.profile-identity-sports li')).toHaveCount(2);
  await mkdir('.local/screenshots',{recursive:true});
  await page.screenshot({path:'.local/screenshots/profile-sports-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'.local/screenshots/profile-sports-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Eliminar Natación',exact:true}).click();
  await expect(page.getByRole('button',{name:'Agregar Natación',exact:true})).toHaveAttribute('aria-pressed','false');
  await expect(page.locator('.profile-sports-selected').getByText('Principal',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Guardar deportes',exact:true}).click();
  await expect(page.locator('.profile-identity-sports li')).toHaveCount(1);
  await page.reload();await page.getByRole('tab',{name:'Deportes',exact:true}).click();
  await expect(page.getByRole('button',{name:'Seleccionado: Running',exact:true})).toBeVisible();
  await expect(page.locator('.profile-sports-selected').getByText('Principal',{exact:true})).toHaveCount(0);
  expect(errors).toEqual([]);console.log('Deportes: selección, principal, búsqueda, guardado y responsive OK');
} finally {await browser?.close();await vite?.close();await new Promise(resolve=>server.close(resolve));await db.$disconnect();}
