import { chromium,expect } from '@playwright/test';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import { mkdir } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PrismaClient,Prisma } from '../prisma/client/index.js';
import { createApp } from '../server/app.js';
import { readConfig } from '../server/config.js';
const url=new URL(process.env.TEST_DATABASE_URL);
if(!['localhost','127.0.0.1'].includes(url.hostname)||url.pathname!=='/invictus_test')throw Error('Solo invictus_test local');
const db=new PrismaClient({datasources:{db:{url:url.href}}});
const origin='http://localhost:5174';
const app=await createApp({database:db,Prisma,config:readConfig({...process.env,DATABASE_URL:url.href,NODE_ENV:'test',STORAGE_DRIVER:'local',WEB_ORIGINS:origin,UPLOAD_DIRECTORY:'.local/test-uploads'})});
const server=app.listen(3101);let vite,browser;
try {
  vite=await createServer({configFile:false,root:'client',plugins:[react()],server:{host:'localhost',port:5174,strictPort:true,proxy:{'/api':'http://localhost:3101'}}});await vite.listen();
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const username='ui_'+randomUUID().replaceAll('-','').slice(0,24),email=randomUUID()+'@example.test';
  const registered=await page.request.post(origin+'/api/auth/register',{headers:{Origin:origin},data:{username,email,password:'abcdefgh'}});
  expect(registered.status()).toBe(201);
  await page.goto(origin+'/#/perfil');await page.getByRole('heading',{name:'Perfil',exact:true}).waitFor();
  await expect(page.getByLabel('Nombre de usuario')).toHaveValue(username);

 await page.getByRole('tab',{name:'Trayectoria',exact:true}).click();
 await expect(page.getByText('Agrega tu primera participación.',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Agregar participación',exact:false}).click();
 await page.getByLabel('Nombre del evento',{exact:true}).fill('Carrera de mi historia');
 const catalog=(await page.request.get(origin+'/api/disciplines')).json();const disciplines=await catalog;
 await page.getByLabel('Disciplina',{exact:true}).selectOption(disciplines[0].id);
 await page.getByLabel('Año',{exact:true}).fill('2020');
 await page.getByRole('button',{name:'Guardar participación',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Carrera de mi historia',exact:true})).toBeVisible();
 await expect(page.getByText('Fecha exacta no indicada',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Editar Carrera de mi historia',exact:true}).click();
 await page.getByLabel('Marca / tiempo / resultado').fill('47:32');
 await page.getByRole('button',{name:'Guardar participación',exact:true}).click();
 await expect(page.getByText('47:32',{exact:true})).toBeVisible();
 await page.getByLabel('Filtrar por disciplina').selectOption(disciplines[0].id);
 await mkdir('.local/screenshots',{recursive:true});await page.screenshot({path:'.local/screenshots/trajectory-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'.local/screenshots/trajectory-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Eliminar Carrera de mi historia',exact:true}).click();
 await page.getByRole('button',{name:'Confirmar eliminación',exact:true}).click();
 await expect(page.getByText('Agrega tu primera participación.',{exact:false})).toBeVisible();
 expect(errors).toEqual([]);console.log('Trayectoria: crear, editar, filtrar y eliminar; desktop/mobile sin overflow ni errores.');
} finally {await browser?.close();await vite?.close();await new Promise(resolve=>server.close(resolve));await db.$disconnect();}
