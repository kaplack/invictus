import { chromium,expect } from '@playwright/test';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import { mkdir } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PrismaClient,Prisma } from '../prisma/client/index.js';
import { createApp } from '../server/app.js';
import { readConfig } from '../server/config.js';
const url=new URL(process.env.TEST_DATABASE_URL);
if(!['localhost','127.0.0.1'].includes(url.hostname)||url.pathname!=='/invictus_test')throw Error('Solo invictus_test local');
const db=new PrismaClient({datasources:{db:{url:url.href}}});
const origin='http://localhost:5174';
const app=await createApp({database:db,Prisma,config:readConfig({...process.env,DATABASE_URL:url.href,NODE_ENV:'test',STORAGE_DRIVER:'local',WEB_ORIGINS:origin,UPLOAD_DIRECTORY:'.local/test-uploads'})});
const server=app.listen(3101);let vite,browser;
try {
  vite=await createServer({configFile:false,root:'client',plugins:[react()],server:{host:'localhost',port:5174,strictPort:true,proxy:{'/api':'http://localhost:3101'}}});await vite.listen();
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const username='ui_'+randomUUID().replaceAll('-','').slice(0,24),email=randomUUID()+'@example.test';
  const registered=await page.request.post(origin+'/api/auth/register',{headers:{Origin:origin},data:{username,email,password:'abcdefgh'}});
  expect(registered.status()).toBe(201);
  await page.goto(origin+'/#/perfil');await page.getByRole('heading',{name:'Perfil',exact:true}).waitFor();
  await expect(page.getByLabel('Nombre de usuario')).toHaveValue(username);

  await page.getByRole('tab',{name:'Presencia digital',exact:true}).click();
  await expect(page.getByRole('navigation',{name:'Enlaces de presencia digital'})).toHaveCount(0);
  await page.getByRole('textbox',{name:'Sitio web',exact:true}).fill('alanburga.com');
  await page.getByRole('textbox',{name:'Instagram',exact:true}).fill('https://example.com/alan');
  await page.getByRole('button',{name:'Guardar enlaces',exact:true}).click();
  await expect(page.locator('#digital-error-INSTAGRAM')).toBeVisible();
  await page.getByRole('textbox',{name:'Instagram',exact:true}).fill('@alanburga');
  await page.getByRole('textbox',{name:'TikTok',exact:true}).fill('alanburga');
  await page.getByRole('textbox',{name:'YouTube',exact:true}).fill('https://youtube.com/@alanburga');
  await page.getByRole('button',{name:'Guardar enlaces',exact:true}).click();
  await expect(page.getByText('Enlaces guardados.',{exact:true})).toBeVisible();
  const icons=page.getByRole('navigation',{name:'Enlaces de presencia digital'});
  await expect(icons.getByRole('link',{name:'Instagram',exact:true})).toHaveAttribute('href','https://instagram.com/alanburga');
  await expect(icons.getByRole('link',{name:'Instagram',exact:true})).toHaveAttribute('rel','noopener noreferrer');
  await expect(icons.getByRole('link',{name:'Instagram',exact:true})).toHaveAttribute('target','_blank');
  await expect(icons.getByRole('link',{name:'Facebook',exact:true})).toHaveCount(0);
  await mkdir('.local/screenshots',{recursive:true});
  await page.screenshot({path:'.local/screenshots/digital-presence-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('textbox',{name:'Instagram',exact:true})).toHaveValue('https://instagram.com/alanburga');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'.local/screenshots/digital-presence-mobile.png',fullPage:true});
  await page.getByRole('textbox',{name:'Instagram',exact:true}).fill('');
  await page.getByRole('button',{name:'Guardar enlaces',exact:true}).click();
  await expect(icons.getByRole('link',{name:'Instagram',exact:true})).toHaveCount(0);
  await page.reload();await page.getByRole('tab',{name:'Presencia digital',exact:true}).click();
  await expect(page.getByRole('textbox',{name:'Sitio web',exact:true})).toHaveValue('https://alanburga.com/');
  await expect(page.getByRole('textbox',{name:'Instagram',exact:true})).toHaveValue('');
  expect(errors).toEqual([]);console.log('Presencia digital: guardado, validación, iconos y responsive OK');
} finally {await browser?.close();await vite?.close();await new Promise(resolve=>server.close(resolve));await db.$disconnect();}
