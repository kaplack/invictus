import { chromium, expect } from '@playwright/test';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import { mkdir } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PrismaClient, Prisma } from '../prisma/client/index.js';
import { createApp } from '../server/app.js';
import { readConfig } from '../server/config.js';
const url = new URL(process.env.TEST_DATABASE_URL);
if (!['localhost','127.0.0.1'].includes(url.hostname) || url.pathname !== '/invictus_test') throw new Error('Solo invictus_test local');
const db = new PrismaClient({ datasources: { db: { url: url.href } } });
const origin = 'http://localhost:5174';
const app = await createApp({ database: db, Prisma, config: readConfig({ ...process.env, DATABASE_URL: url.href, NODE_ENV: 'test', STORAGE_DRIVER: 'local', WEB_ORIGINS: origin, UPLOAD_DIRECTORY: '.local/test-uploads' }) });
const server = app.listen(3101);
let vite, browser;
try {
  vite = await createServer({ configFile: false, root: 'client', plugins: [react()], server: { host: 'localhost', port: 5174, strictPort: true, proxy: { '/api': 'http://localhost:3101' } } });
  await vite.listen(); browser = await chromium.launch({ channel: 'msedge', headless: true });
  const owner = await browser.newContext(), participant = await browser.newContext();
  const post = async (context,path,data,method='POST') => {
    const r = await context.request.fetch(origin+'/api'+path,{ method,headers:{Origin:origin},data });
    if (!r.ok()) throw new Error(`${path}: ${r.status()} ${await r.text()}`);
    return r.json();
  };
  const register = (context,name) => post(context,'/auth/register',{ name,lastName:'Piloto',email:`${randomUUID()}@example.test`,password:'Invictus-Test-2026!' });
  const ownerUser = await register(owner,'Ana'); await register(participant,'María');
  const team = await post(owner,'/teams',{name:'Nadadores del Callao'});
  const method = await post(owner,`/teams/${team.id}/payment-methods`,{type:'YAPE',label:'Yape del Team',phone:'999123456',holderName:'Ana Piloto'});
  const catalog = await (await owner.request.get(origin+'/api/disciplines')).json();
  const event = await post(owner,'/events/mine',{teamId:team.id,disciplineId:catalog[0].id,title:'Travesía del Callao',description:'Encuentro con categorías y revisión de inscripciones.',startsAt:'2027-09-01T14:00:00Z',timeZone:'America/Lima',venue:'Callao',maxCapacity:10});
  const category = await post(owner,`/events/${event.id}/categories`,{name:'Adultos 1 km',priceCents:5000,currency:'PEN',minAge:18,capacity:5});
  await post(owner,`/events/${event.id}/payment-methods`,{methodIds:[method.id]},'PUT');
  await post(owner,`/events/mine/${event.id}/submit`,{});
  await db.user.update({where:{id:ownerUser.user.id},data:{role:'ADMIN'}});
  await post(owner,`/events/manage/${event.id}/review`,{decision:'APPROVE'});
  const page = await participant.newPage(), reviewer = await owner.newPage();
  const errors=[]; for(const p of [page,reviewer])p.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:390,height:844}); await reviewer.setViewportSize({width:1440,height:1000});
  await page.goto(origin+'/#/eventos/'+event.publicSlug);
  await page.getByRole('button',{name:'Inscribirme por categoría'}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByRole('combobox').first().selectOption(category.id);
  await dialog.getByLabel('Fecha de nacimiento',{exact:true}).fill('2000-01-01');
  await dialog.getByRole('combobox').last().selectOption(method.id);
  const file={name:'comprobante.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jA1sAAAAASUVORK5CYII=','base64')};
  await dialog.locator('input[type=file]').setInputFiles(file);
  await mkdir('.local/screenshots',{recursive:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Overflow inscripción móvil');
  await page.screenshot({path:'.local/screenshots/category-enrollment-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Enviar inscripción',exact:true}).click();
  await expect(page.locator('.mobile-records').getByText('Pendiente de revisión del Team',{exact:true})).toBeVisible();
  await reviewer.goto(origin+'/#/mis-eventos');
  await reviewer.getByRole('button',{name:'Ver inscritos',exact:true}).click();
  await reviewer.getByRole('button',{name:'Ver y revisar',exact:true}).click();
  const review=reviewer.getByRole('dialog');
  await review.getByRole('combobox').selectOption('OBSERVED');
  await review.getByLabel('Motivo',{exact:true}).fill('Adjunta una imagen más legible.');
  await review.getByRole('button',{name:'Guardar revisión'}).click();
  await expect(review.getByText('Observada: requiere corrección',{exact:true})).toBeVisible();
  await reviewer.screenshot({path:'.local/screenshots/category-review-desktop.png',fullPage:true});
  await page.reload(); await page.getByRole('button',{name:'Corregir inscripción'}).click();
  await expect(dialog.getByText('Adjunta una imagen más legible.',{exact:true}).first()).toBeVisible();
  await dialog.locator('input[type=file]').setInputFiles({...file,name:'corregido.png'});
  await dialog.getByRole('button',{name:'Reenviar inscripción'}).click();
  await expect(dialog.getByText('Pendiente de revisión del Team',{exact:true}).first()).toBeVisible();
  await reviewer.reload(); await reviewer.getByRole('button',{name:'Ver inscritos',exact:true}).click();
  await reviewer.getByRole('button',{name:'Ver y revisar',exact:true}).click();
  await review.getByRole('button',{name:'Guardar revisión'}).click();
  await expect(review.getByText('Aceptada',{exact:true}).first()).toBeVisible();
  await page.reload(); await page.getByRole('button',{name:'Ver inscripción',exact:true}).click();
  await expect(dialog.getByText('Aceptada',{exact:true}).first()).toBeVisible();
  await page.screenshot({path:'.local/screenshots/category-confirmed-mobile.png',fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Overflow detalle móvil');
  if(errors.length)throw Error(errors.join('\n'));
  console.log('Piloto UI OK: inscripción pagada, observación, corrección, aceptación y escritorio/móvil.');
} finally {
  await browser?.close(); await vite?.close(); await new Promise(resolve=>server.close(resolve)); await db.$disconnect();
}
