import { chromium, expect } from '@playwright/test';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import { mkdir } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PrismaClient, Prisma } from '../prisma/client/index.js';
import { createApp } from '../server/app.js';
import { readConfig } from '../server/config.js';
const url = new URL(process.env.TEST_DATABASE_URL);
if (!['localhost', '127.0.0.1'].includes(url.hostname) || url.pathname !== '/invictus_test') throw new Error('Solo invictus_test local');
const db = new PrismaClient({ datasources: { db: { url: url.href } } });
const origin = 'http://localhost:5174';
const app = await createApp({ database: db, Prisma, config: readConfig({ ...process.env, DATABASE_URL: url.href, NODE_ENV: 'test', STORAGE_DRIVER: 'local', WEB_ORIGINS: origin, UPLOAD_DIRECTORY: '.local/test-uploads' }) });
const server = app.listen(3101);
let vite, browser;
try {
  vite = await createServer({ configFile: false, root: 'client', plugins: [react()], server: { host: 'localhost', port: 5174, strictPort: true, proxy: { '/api': 'http://localhost:3101' } } });
  await vite.listen(); browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext();
  const api = (path, data) => context.request.post(origin + '/api' + path, { headers: { Origin: origin }, data });
  expect((await api('/auth/register', { name: 'Ana', lastName: 'Categorías', email: `${randomUUID()}@example.test`, password: 'Invictus-Test-2026!' })).status()).toBe(201);
  const team = await (await api('/teams', { name: 'Nadadores del Callao' })).json();
  const page = await context.newPage(); await page.setViewportSize({ width: 1440, height: 1000 });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin + '/#/mis-teams/' + team.id);
  await page.getByRole('button', { name: 'Añadir método de pago' }).click();
  await page.getByLabel('Etiqueta (ej. Yape tesorería)').fill('Yape tesorería');
  await page.getByLabel('Titular', { exact: true }).fill('Ana Categorías');
  await page.getByLabel('Celular peruano (9 dígitos)').fill('999123456');
  await page.getByRole('button', { name: 'Guardar método', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.goto(origin + '/#/mis-eventos');
  await page.getByRole('button', { name: 'Crear evento +' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox').first().selectOption(team.id);
  await dialog.locator('select[name="disciplineId"]').selectOption({ label: 'Natación' });
  await page.getByLabel('Título', { exact: true }).fill('Travesía de natación');
  await page.getByLabel('Descripción', { exact: true }).fill('Encuentro organizado por nuestro Team.');
  await page.getByLabel('Fecha y hora de Lima').fill('2027-09-01T09:00');
  await page.getByLabel('Lugar', { exact: true }).fill('La Punta');
  await page.getByRole('button', { name: 'Guardar evento', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: 'Categorías y pagos', exact: true }).click();
  await page.getByRole('button', { name: 'Añadir categoría' }).click();
  await page.getByLabel('Nombre', { exact: true }).fill('Adultos 1 km');
  await page.getByLabel('Precio (0 para gratis)').fill('50');
  await page.getByLabel('Cupo de categoría (opcional)').fill('20');
  await page.getByLabel('Edad mínima (opcional)').fill('18');
  await page.getByRole('button', { name: 'Guardar categoría', exact: true }).click();
  await expect(dialog.locator('table').getByText('Adultos 1 km')).toBeVisible();
  await page.getByRole('checkbox', { name: /Yape tesorería/ }).check();
  await page.getByRole('button', { name: 'Guardar métodos del evento' }).click();
  await expect(page.getByText('Métodos guardados.', { exact: true })).toBeVisible();
  await mkdir('.local/screenshots', { recursive: true });
  await page.screenshot({ path: '.local/screenshots/event-setup-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(dialog.locator('.mobile-records').getByText('Adultos 1 km')).toBeVisible();
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Overflow móvil');
  await page.screenshot({ path: '.local/screenshots/event-setup-mobile.png', fullPage: true });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Enviar a revisión', exact: true }).click();
  await expect(page.locator('.mobile-records').getByText('En revisión por Invictus', { exact: true })).toBeVisible();
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Configuración UI OK: método del Team, disciplina, categoría, selección de pago y envío a revisión; escritorio/móvil.');
} finally {
  await browser?.close(); await vite?.close(); await new Promise(resolve => server.close(resolve)); await db.$disconnect();
}
