import { chromium, expect } from '@playwright/test';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import { mkdir } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PrismaClient, Prisma } from '../prisma/client/index.js';
import { createApp } from '../server/app.js';
import { readConfig } from '../server/config.js';

const url = new URL(process.env.TEST_DATABASE_URL);
if (!['localhost', '127.0.0.1'].includes(url.hostname) || url.pathname !== '/invictus_test') throw new Error('Solo invictus_test local');
const db = new PrismaClient({ datasources: { db: { url: url.href } } });
const origin = 'http://localhost:5174';
const app = await createApp({ database: db, Prisma, config: readConfig({ ...process.env, DATABASE_URL: url.href, NODE_ENV: 'test', STORAGE_DRIVER: 'local', WEB_ORIGINS: origin, UPLOAD_DIRECTORY: '.local/test-uploads' }) });
const server = app.listen(3101);
let vite, browser;
try {
  vite = await createServer({ configFile: false, root: 'client', plugins: [react()], server: { host: 'localhost', port: 5174, strictPort: true, proxy: { '/api': 'http://localhost:3101' } } });
  await vite.listen();
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin + '/#/acceso');
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click();
  await page.getByLabel('Nombre', { exact: true }).fill('Lucía');
  await page.getByLabel('Apellidos').fill('Piloto');
  await page.getByLabel('Correo electrónico').fill(`teams-ui-${randomUUID()}@example.test`);
  await page.getByLabel('Contraseña').fill('Invictus-Test-2026!');
  await page.getByRole('button', { name: 'Crear cuenta →', exact: true }).click();
  await page.getByRole('heading', { name: 'Mi perfil', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Mi cuenta: Lucía' }).click();
  await page.getByRole('link', { name: 'Mis Teams', exact: true }).click();
  await page.getByRole('heading', { name: 'Tu próximo evento empieza con un equipo.' }).waitFor();
  await page.getByRole('button', { name: 'Crear Team', exact: true }).click();
  await page.getByLabel('Nombre del Team (obligatorio)').fill('Nadadores del Callao');
  await page.getByLabel('Descripción (opcional)').fill('Entrenamos juntos y organizamos encuentros de natación.');
  await page.getByLabel('Correo de contacto (opcional)').fill('contacto@example.test');
  await page.getByRole('dialog').getByRole('button', { name: 'Crear Team', exact: true }).click();
  await page.getByRole('heading', { name: 'Nadadores del Callao', exact: true }).waitFor();
  const teamUrl = page.url();
  const other = await browser.newContext();
  const email = `teams-member-${randomUUID()}@example.test`;
  const registered = await other.request.post(origin + '/api/auth/register', { headers: { Origin: origin }, data: { name: 'Mario', lastName: 'Prueba', email, password: 'Invictus-Test-2026!' } });
  expect(registered.status()).toBe(201);
  await page.getByRole('button', { name: 'Agregar miembro' }).click();
  await page.getByLabel('Correo de su cuenta en Invictus').fill(email);
  await page.getByRole('button', { name: 'Guardar miembro' }).click();
  await expect(page.locator('table').getByText('Mario Prueba', { exact: true })).toBeVisible();
  const memberPage = await other.newPage(); await memberPage.goto(teamUrl);
  await memberPage.getByRole('heading', { name: 'Nadadores del Callao', exact: true }).waitFor();
  await expect(memberPage.getByRole('button', { name: 'Editar Team' })).toHaveCount(0);
  await expect(memberPage.getByRole('button', { name: 'Agregar miembro' })).toHaveCount(0);
  const row = page.getByRole('row').filter({ hasText: 'Mario Prueba' });
  await row.getByRole('button', { name: 'Cambiar rol' }).click();
  await page.getByRole('dialog').getByRole('combobox').selectOption('ADMIN');
  await page.getByRole('button', { name: 'Guardar miembro' }).click();
  await expect(row.getByText('Administrador', { exact: true })).toBeVisible();
  await memberPage.reload();
  await memberPage.getByRole('button', { name: 'Editar Team' }).click();
  await memberPage.getByLabel('Teléfono (opcional)', { exact: true }).fill('999111222');
  await memberPage.getByRole('button', { name: 'Guardar cambios' }).click();
  await expect(memberPage.getByText('999111222', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('heading', { name: 'Miembros', exact: true }).waitFor();
  await mkdir('.local/screenshots', { recursive: true });
  await page.screenshot({ path: '.local/screenshots/teams-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('.mobile-records').getByText('Mario Prueba', { exact: true })).toBeVisible();
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Overflow móvil');
  await page.screenshot({ path: '.local/screenshots/teams-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Editar Team' }).click();
  await page.getByLabel('Nombre del Team (obligatorio)').focus();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Editar Team' })).toBeFocused();
  const ownCard = page.locator('.mobile-records article').filter({ hasText: 'Lucía Piloto (tú)' });
  await ownCard.getByRole('button', { name: 'Cambiar rol' }).click();
  await page.getByRole('dialog').getByRole('combobox').selectOption('MEMBER');
  await page.getByRole('button', { name: 'Guardar miembro' }).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('al menos un propietario');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Teams UI OK: creación, miembro/admin, edición, móvil, foco y último owner.');
} finally {
  await browser?.close(); await vite?.close(); await new Promise(resolve => server.close(resolve)); await db.$disconnect();
}
